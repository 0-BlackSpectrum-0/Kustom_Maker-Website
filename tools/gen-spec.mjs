// tools/gen-spec.mjs
import fs from 'node:fs';
import path from 'node:path';

const enumsPath = path.resolve('spec/enums.json');
const modulesPath = path.resolve('spec/modules.json');
const defaultsPath = path.resolve('spec/defaults.json');
const outputPath = path.resolve('src/core/spec/generated.ts');

const enums = JSON.parse(fs.readFileSync(enumsPath, 'utf8'));
const modules = JSON.parse(fs.readFileSync(modulesPath, 'utf8'));
const defaults = JSON.parse(fs.readFileSync(defaultsPath, 'utf8'));

let out = `// Auto-generated by tools/gen-spec.mjs - DO NOT EDIT MANUALLY\n\n`;

// 1. Enums
out += `// --- ENUMS ---\n\n`;

const validEnumNames = [];

for (const [name, values] of Object.entries(enums)) {
  if (!Array.isArray(values)) continue;
  // Sanitize variable name if needed
  const safeName = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(name) ? name : `Enum_${name}`;
  validEnumNames.push([name, safeName]);

  const sortedVals = Array.from(new Set(values.map(String))).sort();
  out += `export const ${safeName}Values = [\n`;
  for (const v of sortedVals) {
    out += `  ${JSON.stringify(v)},\n`;
  }
  out += `] as const;\n`;
  out += `export type ${safeName} = (typeof ${safeName}Values)[number];\n\n`;
}

out += `export const ALL_ENUMS = {\n`;
for (const [rawName, safeName] of validEnumNames) {
  out += `  ${JSON.stringify(rawName)}: ${safeName}Values,\n`;
}
out += `} as const;\n\n`;

out += `export function isEnum<K extends keyof typeof ALL_ENUMS>(enumName: K, v: unknown): v is (typeof ALL_ENUMS)[K][number] {
  const list = ALL_ENUMS[enumName] as readonly unknown[];
  return typeof v === 'string' && list.includes(v);
}\n\n`;

// 2. Module Types
out += `// --- MODULE TYPES ---\n\n`;
const moduleNames = Object.keys(modules);
out += `export const MODULE_TYPES = [\n`;
for (const m of moduleNames) {
  out += `  ${JSON.stringify(m)},\n`;
}
out += `] as const;\n`;
out += `export type ModuleType = (typeof MODULE_TYPES)[number];\n\n`;

// 3. Module Metadata (sections and properties)
out += `// --- MODULE METADATA ---\n\n`;
out += `export const MODULE_SPECS = ${JSON.stringify(modules, null, 2)} as const;\n\n`;

// 4. Defaults
out += `// --- DEFAULTS ---\n\n`;
out += `export const SPEC_DEFAULTS = ${JSON.stringify(defaults, null, 2)} as const;\n\n`;

fs.writeFileSync(outputPath, out, 'utf8');
console.log(`Successfully generated ${outputPath}`);
